     * import('@.ORG.fc.Options');
     * 用法：
     * 1：
     * echo Options::get('table_1.field_1.key_2', function () {
     *      return 'default value';
     *  });
     ***********************************************************
     * 2:
     * $arr = Options::get('table_1.field_1', 'default value');
     * echo $arr['key_1'];
     * ************************************************************
     */
    public static function get( $key, $default = null)
    {
        $options = self::option();
        
        if (is_null($key)) {
            return $options; 
        }
        
        if (isset($options[$key])) {
            return $options[$key];
        }
        
        foreach (explode('.', $key) as $segment) {
            if (! is_array($options) || ! array_key_exists($segment, $options)) {
                return value($default);
            }
            
            $options = $options[$segment];
        }
        
        return $options;
        
    }
    

    

