            if (empty($cardName)) {
                $this->error("一卡通名称不能为空");
            }
            if (empty($belongAdminId)) {
                $this->error("请选择归属管理员");
            }
            // if (empty($unitId)) {
            //     $this->error("请选择归属单位");
            // }
            if (empty($storeId)) {
                $this->error("请填写关联店铺ID");
            }
            if (!M('Merchant_store')->where(['store_id' => $storeId, 'status' => ['neq', 4]])->find()) {
                $this->error("店铺未查询到或者已被删除");
            }

            $data = [
                'card_name' => $cardName,
                'intro' => $intro,
                'admin_id' => $this->system_session['id'],
                'belong_admin_id' => $belongAdminId,
                //'unit_id' => $unitId,
                'store_id' => $storeId,
                'status'=> I('post.status',0,'intval'),
                'use_store_ids'=>I('post.use_store_ids','','trim'),
            ];
