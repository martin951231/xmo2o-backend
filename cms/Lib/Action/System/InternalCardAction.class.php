        $getupload_dir = "/upload/excel/card/" . date('Ymd') . '/';
        $upload_dir = "." . $getupload_dir;
        if (!is_dir($upload_dir)) {
            mkdir($upload_dir, 0777, true);
        }
        import('ORG.Net.UploadFile');
        $upload = new UploadFile();
        $upload->maxSize = 10 * 1024 * 1024;
        $upload->allowExts = array('xls', 'xlsx');
        $upload->allowTypes = array(); // 允许上传的文件类型 留空不做检查
        $upload->savePath = $upload_dir;
        $upload->thumb = false;
        $upload->thumbType = 0;
        $upload->imageClassPath = '';
        $upload->thumbPrefix = '';
        $upload->saveRule = 'uniqid';
        if ($upload->upload()) {
            $uploadList = $upload->getUploadFileInfo();
            require_once APP_PATH . 'Lib/ORG/phpexcel/PHPExcel/IOFactory.php';
            $path = $uploadList['0']['savepath'] . $uploadList['0']['savename'];
            $fileType = PHPExcel_IOFactory::identify($path); //文件名自动判断文件类型
            $objReader = PHPExcel_IOFactory::createReader($fileType);
            $excelObj = $objReader->load($path);
            $result = $excelObj->getActiveSheet()->toArray(null, false, true, true);
            $card_db = M('internal_membership_card');
            $card_log_db = M('internal_membership_card_log');

            // 遍历每一行，删除空行
            foreach ($result as $key => $row) {
                if (empty(array_filter($row))) {
                    unset($result[$key]);
                }
            }

            $update_card_data = [];
            $province_id = 0;
            $city_id = 0;
            $area_id = 0;
            $have_card_id_arr = [];
            foreach ($result as $row => $value) {
                if ($row == 1) {
                    continue;
                }
                $_card_data = [];
                $_card_data['card_id'] = htmlspecialchars(trim($value['A']), ENT_QUOTES);
                $_card_data['recharge_money'] = htmlspecialchars(trim($value['B']), ENT_QUOTES);
                if (in_array($_card_data['card_id'], $have_card_id_arr)) {
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行充值卡号重复']);
                }
                $have_card_id_arr[] = $_card_data['card_id'];

                if (empty($_card_data['card_id']) || empty($_card_data['recharge_money'])) {
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行数据未填完整']);
                }
                if (!is_numeric($_card_data['recharge_money'])) {
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行充值金额有误']);
                }
                $_card_data['recharge_money'] = sprintf('%.2f', $_card_data['recharge_money']);
                /*if ($_card_data['recharge_money'] <= 0) {
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行充值金额不能小于0']);
                }*/

                $_card_info = $card_db->where(['card_id' => $_card_data['card_id']])->find();
                if (!$_card_info) {
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行数据一卡通卡号[' . $_card_data['card_id'] . ']不存在']);
                }
                if ($_card_info['status'] == 0) {
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行数据一卡通卡号[' . $_card_data['card_id'] . ']已禁用，禁止充值']);
                }
                if(!is_null($cardTypes) && !in_array($_card_info['card_name'], $cardTypes)){
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行数据一卡通类型无充值权限']);
                }
                if ($this->admin_area_id > 0 && $_card_info['area_id'] != $this->admin_area_id) {
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行数据一卡通卡号[' . $_card_data['card_id'] . ']不存在~']);
                }
                if ($area_id == 0) {
                    $province_id = $_card_info['province_id'];
                    $city_id = $_card_info['city_id'];
                    $area_id = $_card_info['area_id'];
                }
                if ($area_id != $_card_info['area_id']) {
                    $this->dexit(['error' => 1, 'msg' => '第' . $row . '行数据一卡通卡号[' . $_card_data['card_id'] . ']地区不一致，请选择同一地区的一卡通充值']);
                }

                $_card_data['card_info'] = $_card_info;

                $update_card_data[$row] = $_card_data;
            }
            if ($area_id == 0) {
                $this->dexit(['error' => 1, 'msg' => '一卡通地区信息不全，请选择同一地区的一卡通充值']);
            }
            $batch_no = \internalCard\InternalCardService::genRechargeBatchNo();

            // 开启事务
            $database = D('');
            $database->startTrans();
            $all_recharge_money = 0;
            foreach ($update_card_data as $_key => $_val) {
                $time = time();
                $_card_info = $_val['card_info'];

                $_money = $_val['recharge_money'];
                $all_recharge_money += $_money;
                $_update_card_data = [];
                $_update_card_data['balance_money'] = sprintf('%.2f', $_money + $_card_info['balance_money']);
                $_update_card_data['last_time'] = time();
                $card_ret = $card_db->where(['id' => $_card_info['id']])->save($_update_card_data);
                if ($card_ret === false) {
                    $database->rollback();
                    $this->dexit(['error' => 1, 'msg' => '操作失败']);
                }

                //插入审核日志
                if ($_card_info['status'] == 0) {
                    $status = '禁止';
                } else if ($_card_info['status'] == 1) {
                    $status = '正常';
                } else {
                    $status = '未审核';
                }

                $condition_card_log = [];
                $condition_card_log['card_id'] = $_card_info['card_id'];
                $condition_card_log['operation_type'] = 1;
                $condition_card_log['before_balance'] = $_card_info['balance_money'];
                $condition_card_log['after_balance'] = $_update_card_data['balance_money'];
                $condition_card_log['money'] = $_money;
                $condition_card_log['system_id'] = $this->system_session['id'];
                $condition_card_log['describe'] = "系统管理员{$this->system_session['account']}({$this->system_session['id']})". '给一卡通(' . $_card_info['card_id'] . ')充值' . $_money . '元,余额'.$_update_card_data['balance_money'].'元，状态' . $status;
                $condition_card_log['create_time'] = $time;
                $condition_card_log['deduction_batch_no'] = $batch_no;
                $log_ret = $card_log_db->add($condition_card_log);
                if ($log_ret === false) {
                    $database->rollback();
                    $this->dexit(['error' => 1, 'msg' => '操作失败']);
                }
            }

            //插入批次充值记录信息
            $recharge_insert = [];
            $recharge_insert['batch_no'] = $batch_no;
            $recharge_insert['total_money'] = $all_recharge_money;
            $recharge_insert['create_system_id'] = $this->system_session['id'];
            $recharge_insert['province_id'] = $province_id;
            $recharge_insert['city_id'] = $city_id;
            $recharge_insert['area_id'] = $area_id;
            $recharge_ret = M('internal_membership_card_recharge')->add($recharge_insert);
            if (!$recharge_ret) {
                $database->rollback();
                $this->dexit(['error' => 1, 'msg' => '操作失败']);
            }

            $database->commit();
            $this->dexit(['error' => 0]);
        }
    }

