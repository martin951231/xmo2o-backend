    public function import(){
        if ($this->system_session['level'] <> 2) {
            $cardTypes = D('Admin')->getCardTypeByAdmin($this->system_session);
            if (empty($cardTypes)) {
                $this->dexit(array('error' => 1, 'msg' => '当前管理员还未绑定一卡通类型，禁止导入'));
            }
        }

        if ($_FILES['file']['error'] != 4) {
            import('ORG.Util.Dir');
            Dir::delDirnotself('./upload/excel/card');

            $getupload_dir = "/upload/excel/card/" . date('Ymd') . '/';
            $upload_dir = "." . $getupload_dir;
            if (!is_dir($upload_dir)) {
                mkdir($upload_dir, 0777, true);
            }
            import('ORG.Net.UploadFile');
            $upload = new UploadFile();
            $upload->maxSize = 10 * 1024 * 1024;
            $upload->allowExts = array('xls', 'xlsx');
            $upload->allowTypes = array(); // 允许上传的文件类型 留空不做检查
            $upload->savePath = $upload_dir;
            $upload->thumb = false;
            $upload->thumbType = 0;
            $upload->imageClassPath = '';
            $upload->thumbPrefix = '';
            $upload->saveRule = 'uniqid';
            if ($upload->upload()) {
                $uploadList = $upload->getUploadFileInfo();
                require_once APP_PATH . 'Lib/ORG/phpexcel/PHPExcel/IOFactory.php';
                $path = $uploadList['0']['savepath'] . $uploadList['0']['savename'];
                $fileType = PHPExcel_IOFactory::identify($path); //文件名自动判断文件类型
                $objReader = PHPExcel_IOFactory::createReader($fileType);
                $excelObj = $objReader->load($path);
                $result = $excelObj->getActiveSheet()->toArray(null, false, true, true);
                $user_db = M('user');
                $card_db = M('internal_membership_card');
                $card_log_db = M('internal_membership_card_log');
                $m_internal_unit = M('internal_unit');
                $m_internal_membership_card_import = M('internal_membership_card_import');

                $unit_list = $m_internal_unit->select();
                $unit_map = array_column($unit_list, null, 'id');

                $import_batch_no = \internalCard\InternalCardService::genImportBatchNo();

                // 遍历每一行，删除空行
                foreach ($result as $key => $row) {
                    if (empty(array_filter($row))) {
                        unset($result[$key]);
                    }
                }

                // 开启事务
                $database = D('');
                $database->startTrans();
                $deduction_unit_arr = [];
                $total_money = 0;
                $province_id = 0;
                $city_id = 0;
                $area_id = 0;
                foreach ($result as $row => $value) {
                    if ($row == 1){
                        continue;
                    }
                    $tmpdata = array();
                    $tmpdata['card_id'] = htmlspecialchars(trim($value['A']), ENT_QUOTES);
                    $tmpdata['card_name'] = htmlspecialchars(trim($value['B']), ENT_QUOTES);
                    $tmpdata['user_name'] = htmlspecialchars(trim($value['D']), ENT_QUOTES);
                    $tmpdata['phone'] = htmlspecialchars(trim($value['E']), ENT_QUOTES);
                    $_password = htmlspecialchars(trim($value['G']), ENT_QUOTES);
                    $unitName = htmlspecialchars(trim($value['C']), ENT_QUOTES);

                    if (!is_null($cardTypes) && !in_array($tmpdata['card_name'], $cardTypes)) {
                        $this->dexit(array('error' => 1, 'msg' => '第' . $row . '行一卡通类型无添加权限'));
                    }

                    //unit_id单位
                    $thisUnit = M('internal_unit')->where(['name' => $unitName])->find();
                    if (!$thisUnit) {
                        $this->dexit(array('error' => 1, 'msg' => '第' . $row . '行归属单位不存在'));
                    }
                    $tmpdata['unit_id'] = $thisUnit['id'];


                    //store_id 读取一卡通名称关联的
                    $thisCard = M('internal_membership_names')->where(['card_name' => $tmpdata['card_name']])->find();
                    if (!$thisCard) {
                        $this->dexit(array('error' => 1, 'msg' => '第' . $row . '行一卡通名称不存在'));
                    }
                    if ($thisCard['status'] != 1) {
                        $this->dexit(array('error' => 1, 'msg' => '第' . $row . '行一卡通名称已禁用'));
                    }
                    $tmpdata['store_id'] = $thisCard['store_id'];

                    if ($_password) {
                        if (strlen($_password) != 6) {
                            $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行密码格式错误，密码必须6位数'));
                        }
                        $tmpdata['password'] = md5($_password);
                    } else {
                        $tmpdata['password'] = md5(substr($tmpdata['phone'], -6));
                    }
                    $tmpdata['balance_money'] = htmlspecialchars(trim($value['F']), ENT_QUOTES);
                    $tmpdata['last_time'] = time();
                    $tmpdata['create_time'] = time();
                    $tmpdata['is_bind'] = 0;
                    $tmpdata['status'] = 1;
                    $tmpdata['import_batch_no'] = $import_batch_no;
                    if (empty($tmpdata['card_id']) or empty($tmpdata['card_name']) or empty($tmpdata['user_name']) or empty($tmpdata['store_id'])){
                        $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行数据未填完整'));
                    }
                    if (!is_numeric($tmpdata['balance_money'])){
                        $database->rollback();
                        $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行数据充值金额错误'));
                    }
                    $tmpdata['balance_money'] = sprintf('%.2f', $tmpdata['balance_money']);
                    if(!preg_match("/^[19][3456789]\d{9}$/", $tmpdata['phone']) && !in_array($tmpdata['phone'], C('sys_conf.special_internal_card_id'))) {
                        $database->rollback();
                        $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行数据手机号格式错误'));
                    }
                    $card = $card_db->where(array('card_id' => $tmpdata['card_id']))->find();
                    if ($card){
                        $database->rollback();
                        $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行数据一卡通卡号['. $tmpdata['card_id'] .']已存在'));
                    }
                    if (!isset($unit_map[$tmpdata['unit_id']])) {
                        $database->rollback();
                        $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行数据关联归属单位['. $tmpdata['unit_id'] .']不存在'));
                    }
                    if (!$unit_map[$tmpdata['unit_id']]['area_id']) {
                        $database->rollback();
                        $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行数据关联归属单位['. $tmpdata['unit_id'] .']未绑定区域，请先绑定'));
                    }
                    if ($this->admin_area_id > 0 && $unit_map[$tmpdata['unit_id']]['area_id'] != $this->admin_area_id) {
                        $database->rollback();
                        $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行数据关联归属单位['. $tmpdata['unit_id'] .']不存在~'));
                    }
                    if ($area_id == 0) {
                        $province_id = $unit_map[$tmpdata['unit_id']]['province_id'];
                        $city_id = $unit_map[$tmpdata['unit_id']]['city_id'];
                        $area_id = $unit_map[$tmpdata['unit_id']]['area_id'];
                    }
                    if ($area_id != $unit_map[$tmpdata['unit_id']]['area_id']) {
                        $this->dexit(['error' => 1, 'msg' => '第' . $row . '行数据一卡通卡号[' . $tmpdata['card_id'] . ']归属单位地区不一致，请选择同一地区的归属单位导入']);
                    }

                    $store = M('merchant_store')->where(array('store_id' => $tmpdata['store_id']))->find();
                    if (!$store){
                        $database->rollback();
                        $this->dexit(array('error' => 1, 'msg' => '第'. $row .'行数据关联店铺['. $tmpdata['store_id'] .']不存在'));
                    }
                    $user = $user_db->where(array('phone' => $tmpdata['phone']))->find();
                    if ($user){
                        $tmpdata['uid'] = $user['uid'];
                        $tmpdata['is_bind'] = 1;
                        $tmpdata['active_time'] = time();
                    }
                    $tmpdata['company_owner'] = $unit_map[$tmpdata['unit_id']]['name'];
                    $tmpdata['province_id'] = $unit_map[$tmpdata['unit_id']]['province_id'];
                    $tmpdata['city_id'] = $unit_map[$tmpdata['unit_id']]['city_id'];
                    $tmpdata['area_id'] = $unit_map[$tmpdata['unit_id']]['area_id'];
                    $card_ret = $card_db->add($tmpdata);
                    if (!$card_ret) {
                        $database->rollback();
                        $this->dexit(array('error' => 1, 'msg' => '操作失败'));
                    }

                    //日志
                    $condition_card_log = [];
                    $condition_card_log['card_id'] = $tmpdata['card_id'];
                    $condition_card_log['system_id'] = $this->system_session['id'];
                    $condition_card_log['describe'] = "系统管理员{$this->system_session['account']}({$this->system_session['id']})".'导入一卡通, 默认余额 '.(string)$tmpdata['balance_money'].'元,状态正常';
                    $condition_card_log['create_time'] = time();
                    $condition_card_log['operation_type'] = 0;
                    $card_log_db->add($condition_card_log);
                    if ($tmpdata['balance_money'] != 0){
                        $condition_card_log['operation_type'] = 1;
                        $condition_card_log['before_balance'] = 0;
                        $condition_card_log['after_balance'] = sprintf('%.2f', $tmpdata['balance_money']);
                        $condition_card_log['money'] = sprintf('%.2f', $tmpdata['balance_money']);
                        $condition_card_log['describe'] = "系统管理员{$this->system_session['account']}({$this->system_session['id']})".'导入一卡通, 充值默认余额 '.$condition_card_log['money'].'元,状态正常';
                        $card_log_id = $card_log_db->add($condition_card_log);
                        if (!$card_log_id) {
                            $database->rollback();
                            $this->dexit(array('error' => 1, 'msg' => '操作失败'));
                        }

                        if (!isset($deduction_unit_arr[$tmpdata['unit_id']])) {
                            $deduction_unit_arr[$tmpdata['unit_id']]['card_recharge_money'] = $tmpdata['balance_money'];
                        } else {
                            $deduction_unit_arr[$tmpdata['unit_id']]['card_recharge_money'] += $tmpdata['balance_money'];
                        }
                        $deduction_unit_arr[$tmpdata['unit_id']]['card_log_id'][] = $card_log_id;
                        $total_money += $tmpdata['balance_money'];
                    }
                }

                //插入批次导入信息
                $insert_import_batch_data = [];
                $insert_import_batch_data['batch_no'] = $import_batch_no;
                $insert_import_batch_data['total_money'] = $total_money;
                $insert_import_batch_data['create_system_id'] = $this->system_session['id'];
                $insert_import_batch_data['province_id'] = $province_id;
                $insert_import_batch_data['city_id'] = $city_id;
                $insert_import_batch_data['area_id'] = $area_id;
                $import_batch_ret = $m_internal_membership_card_import->add($insert_import_batch_data);
                if (!$import_batch_ret) {
                    $database->rollback();
                    $this->dexit(array('error' => 1, 'msg' => '操作失败~'));
                }

                $database->commit();
                $this->dexit(array('error' => 0, 'batch_no' => $import_batch_no));
            }
        }
    }

    public function transaction_count()
    {
        //默认查询最近一个月
        !isset($_GET['start_time']) && $_GET['start_time'] = date('Y-m-d', strtotime('-1 month'));
        !isset($_GET['end_time']) && $_GET['end_time'] = date('Y-m-d');

        $card_id = I('get.card_id', '', 'trim,strip_tags');
        $phone = I('get.phone', '', 'trim,strip_tags');
        $card_name = I('get.card_name', '', 'trim,strip_tags');
        $store_name = I('get.store_name', '', 'trim,strip_tags');
        $start_time = I('get.start_time', '', 'trim,strip_tags');
        $end_time = I('get.end_time', '', 'trim,strip_tags');
        $province_id = I('get.province_idss', 0, 'int');
        $city_id = I('get.city_idss', 0, 'int');
        $area_id = I('get.area_id', 0, 'int');
        $export = I('get.export', '', 'trim,strip_tags');
        $page = I('get.page', 1, 'int');
        $offset = 15;

        $area_list = D('Area')->get_area_list();
        $area_map = array_column($area_list, null, 'area_id');

        $condition_card_log = [];
        $condition_card_log['l.operation_type'] = array('in',[2, 3]);
        if ($card_id){
            $condition_card_log['l.card_id'] = $card_id;
        }
        if ($phone){
            $condition_card_log['c.phone'] = array('like', "%{$phone}%");
        }
        if ($card_name){
            $condition_card_log['c.card_name'] = array('like', "%{$card_name}%");
        }
        if ($store_name){
            $condition_card_log['s.name'] = array('like', "%{$store_name}%");
        }
        if ($start_time && !$end_time) {
            $condition_card_log['l.create_time'] = ['egt', strtotime($start_time)];
        } elseif (!$start_time && $end_time) {
            $condition_card_log['l.create_time'] = ['elt', strtotime($end_time . ' 59:00:00')];
        } elseif ($start_time && $end_time) {
            $condition_card_log['l.create_time'] = ['between', [strtotime($start_time), strtotime($end_time . ' 23:59:59')]];
        }
        if ($province_id) {
            $condition_card_log['s.province_id'] = $province_id;
        }
        if ($city_id) {
            $condition_card_log['s.city_id'] = $city_id;
        }
        if ($area_id) {
            $condition_card_log['s.area_id'] = $area_id;
        }
        if ($this->admin_area_id > 0) {
            $condition_card_log['s.area_id'] = $this->admin_area_id;
        }

        if ($this->system_session['level'] <> 2) {
            $cardTypes = D('Admin')->getCardTypeByAdmin($this->system_session,$card_name);
            if ($cardTypes) {
                $condition_card_log['c.card_name'] = ['IN', $cardTypes];
            } else {
                $condition_card_log['c.card_name'] = null;
            }
        }

        $log_group = 'c.card_name, l.store_id';
        $log_field = 'c.card_name, s.name as store_name, l.store_id, sum(CASE WHEN operation_type = 2 THEN l.money WHEN operation_type = 3 THEN l.money*-1 ELSE 0 END ) as total_money, s.area_id as area_id';
        $log_join = 'INNER join __INTERNAL_MEMBERSHIP_CARD__ c ON l.card_id = c.card_id left join __MERCHANT_STORE__ s ON l.store_id = s.store_id';
        if ($export == 'excel') {
            if ($card_id || $phone) {
                $first_line_map = [['序号', 'auto_serial'], ['一卡通名称', 'card_name'], ['一卡通号', 'card_id'], ['用户电话', 'phone'], ['店铺名称', 'store_name'], ['区域', 'region_str'], ['消费总金额', 'total_money']];
                $log_group .= ', l.card_id';
            } else {
                $first_line_map = [['序号', 'auto_serial'], ['一卡通名称', 'card_name'], ['店铺名称', 'store_name'], ['区域', 'region_str'], ['消费总金额', 'total_money']];
            } 
        }
        $m_card_log = M('internal_membership_card_log');

        //查询数据
        $log_list = $m_card_log->alias('l')->field($log_field)->join($log_join)->where($condition_card_log)->group($log_group)
            ->limit($export == 'excel' ? 0 : (($page - 1) * $offset) . ", {$offset}")->select();
        foreach ($log_list as $key => $val) {
            $log_list[$key]['region_str'] = $area_map[$val['area_id']]['area_ip_desc'] ?? '';
            if (!isset($val['card_id'])) {
                $log_list[$key]['card_id'] = '';
                $log_list[$key]['phone'] = '';
            }
        }
        //导出数据
        if ($export == 'excel') {
            $s_excel = new \service\ExcelService();
            $s_excel->exportExcel($first_line_map, $log_list, '一卡通交易统计');
            exit;
        }

        $sub_query = $m_card_log->alias('l')->field($log_group)->join($log_join)->where($condition_card_log)->group($log_group)->buildSql();
        $log_count = M('')->table($sub_query . ' sub')->count();
        import('@.ORG.system_page');
        $s_page = new Page($log_count, $offset);

        $count_data = $m_card_log->field('sum(CASE WHEN operation_type = 2 THEN l.money WHEN operation_type = 3 THEN l.money*-1 ELSE 0 END ) as total_money')
            ->join('as l left join ' . C('DB_PREFIX') . 'internal_membership_card c ON l.card_id = c.card_id left join '. C('DB_PREFIX') .'merchant_store s ON l.store_id = s.store_id')
            ->where($condition_card_log)
            ->select();
        $this->assign('total_money', $count_data[0]);
        $this->assign('list', $log_list);
        $pagebar = $s_page->show();
        $this->assign('pagebar', $pagebar);
        $this->display();
    }
