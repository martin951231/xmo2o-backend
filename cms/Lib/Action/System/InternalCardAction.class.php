    //指定可使用区域
    public function area()
    {
        $mod = M('internal_membership_names');
        if ($_POST) {
            $id = I('post.name_id', 0, 'intval');
            $areaIds = I('post.area_ids', []);
            if (empty($id)) {
                $this->error("参数有误");
            } else if (empty($areaIds)) {
                $this->error("请选择区域");
            }
            $mod->where(['id' => $id])->save(['use_area_ids' => implode(',', $areaIds)]);
            $this->success("区域保存成功");
        } else{
            $id = I('get.name_id', 0, 'intval');
            if (empty($id)) {
                $this->error("参数有误");
            }
            $areaIds = explode(',', $mod->where(['id' => $id])->getField('use_area_ids'));

            $where = ['area_type' => ['lt', 4], 'is_open' => 1];
            $areaList = D('Area')->where($where)->getField('area_id, area_pid, area_name', true);
            $areaList = array_map(function ($r) use ($areaIds) {
                $r['select'] = in_array($r['area_id'], $areaIds) ? 1 : 0;
                return $r;
            }, $areaList);
    
            $first = array_filter($areaList, function ($r) {
                return $r['area_pid'] == 0;
            });

            //没有区域的城市不显示
            foreach ($first as $k => $f) {
                $second = array_filter($areaList, function ($r) use ($f) {
                    return $f['area_id'] == $r['area_pid'];
                });

                foreach ($second as $sk => $sf) {
                    $three = array_filter($areaList, function ($r) use ($sf) {
                        return $sf['area_id'] == $r['area_pid'];
                    });
                    if ($three) {
                        $second[$sk]['son_list'] = array_values($three);
                        $second[$sk]['select'] = in_array(1, array_column($three, 'select')) ? 1 : 0;
                    } else {
                        unset($second[$sk]);
                    }
                }
                $first[$k]['son_list'] = array_values($second);
                $first[$k]['select'] = in_array(1, array_column($second, 'select')) ? 1 : 0;
            }
            $list = array_values($first);
            $this->assign('area_list', $list);
            $this->display();
        }
    }


    //指定店铺
    public function store()
    {
        $mod = M('internal_membership_names');
        if ($_POST) {
            $id = I('post.name_id', 0, 'intval');
            $storeIds = I('post.store_ids', []);
            $type = I('post.type', '', 'trim');
            if (empty($id) || !in_array($type, ['bind', 'unbind'])) {
                $this->error("参数有误");
            } else if (empty($storeIds)) {
                $this->error("请选择店铺");
            }

            $record = $mod->where(['id' => $id])->find();
            if (empty($record)) {
                $this->error("一卡通类型记录不存在");
            }

            $oldUseStoreids = $record['use_store_ids'] ? explode(',', $record['use_store_ids']) : [];
            if (
                $type == 'bind'
            ) {
                //绑定
                $newStoreids = array_merge($oldUseStoreids, $storeIds);
            } else {
                //解绑
                $newStoreids = array_filter($oldUseStoreids, function ($r) use ($storeIds) {
                    return !in_array($r, $storeIds);
                });
            }
            $newStoreids = array_unique($newStoreids);
            $mod->where(['id' => $id])->save(['use_store_ids' => implode(',', $newStoreids)]);
            $this->success("指定店铺保存成功");
        } else {
            $id = I('get.name_id', 0, 'intval');
            $thisType = $mod->where(['id' => $id])->field('use_store_ids,belong_admin_id')->find();
            if (empty($thisType)) {
                $this->error("会员卡类型不存在");
            }

            //超级管理员或者卡类型归属管理员才允许修改指定店铺
            $canEdit = ($this->system_session['level'] == 2 || $this->system_session['id'] == $thisType['belong_admin_id']);
            $this->assign('canEdit', $canEdit);

            $useStoreIds = explode(',', $thisType['use_store_ids']);

            $where = ['m.status' => 1, 's.status' => ['neq', 4], 's.is_internal_card_pay' => 1];
            
            if ($this->system_session['level'] <> 2 && !isset($_GET['status'])) {
                $_GET['status'] = 1;
            }

            if($_GET['status'] == 1){
                $where['s.store_id'] = ['IN',$useStoreIds];
            }else if($_GET['status'] == 2){
                $where['s.store_id'] = ['NOT IN',$useStoreIds];
            }

            $_GET['keyword'] = trim($_GET['keyword']);
            if (!empty($_GET['keyword'])) {
                if ($_GET['searchtype'] == 'mer_id') {
                    $where['m.mer_id'] = intval($_GET['keyword']);
                } elseif ($_GET['searchtype'] == 'account') {
                    $where['m.account'] = $_GET['keyword'];
                } elseif ($_GET['searchtype'] == 'name') {
                    $where['m.name'] = ['LIKE', '%' . $_GET['keyword'] . '%'];
                } elseif ($_GET['searchtype'] == 'phone') {
                    $where['m.phone'] = $_GET['keyword'];
                } elseif ($_GET['searchtype'] == 'store_name') {
                    $where['s.name'] = ['LIKE', '%' . $_GET['keyword'] . '%'];
                } elseif ($_GET['searchtype'] == 'store_id') {
                    $where['s.store_id'] = intval($_GET['keyword']);
                }
            }

            if($_GET['province_idss']){
                $where['s.province_id'] = intval($_GET['province_idss']);
            }
            if($_GET['city_idss']){
                $where['s.city_id'] = intval($_GET['city_idss']);
            }
            if($_GET['area_id']){
                $where['s.area_id'] = intval($_GET['area_id']);
            }

            $count = D('Merchant')->alias('m')
                ->join('INNER JOIN ' . C('DB_PREFIX') . 'merchant_store AS s ON s.mer_id=m.mer_id')
                ->where($where)
                ->count();

            import('@.ORG.system_page');
            $p = new Page($count, 10);
            $storeList = D('Merchant')->alias('m')
                ->join('INNER JOIN ' . C('DB_PREFIX') . 'merchant_store AS s ON s.mer_id=m.mer_id')
                ->where($where)
                ->field('s.*,m.name as merchant_name')
                ->limit($p->firstRow . ',' . $p->listRows)
                ->select();
            $storeList = array_map(function ($r) use ($useStoreIds) {
                $r['is_bind'] = in_array($r['store_id'], $useStoreIds) ? 1 : 0;
                return $r;
            }, $storeList);
            $this->assign('storeList', $storeList);
            $this->assign('pagebar', $p->show());
            $this->display();
        }
    }

    //一卡通类型关联单位
    public function cardUnits()
    {
        $cardName = I('get.card_name', '', 'trim');
        $unitCards = M('internal_membership_card')->where(['card_name' => $cardName, 'unit_id' => ['gt', 0]])->field('distinct(unit_id)')->select();
       
        $unitIds = array_column($unitCards, 'unit_id');

        if ($_GET['from'] == 'card' && $this->system_session['level'] <> 2) {
            $adminUnitIds = D('Admin')->getUnitIdsByAdmin($this->system_session);
            if ($adminUnitIds) {
                if ($this->admin_area_id > 0) {
                    $adminUnitIds = M('internal_unit')->where(['id' => ['IN', $adminUnitIds], 'area_id' => $this->admin_area_id])->getField('id', true);
                }
                $unitIds = array_intersect($adminUnitIds, $unitIds);
            } else {
                $unitIds = [];
            }
        }

        if ($unitIds) {
            $units = M('internal_unit')->where(['id' => ['IN', $unitIds]])->select();
            $area_list = D('Area')->get_area_list();
            $area_map = array_column($area_list, null, 'area_id');
            foreach ($units as &$_unit) {
                $_unit['card_count'] = M('internal_membership_card')->where(['card_name' => $cardName, 'unit_id' => $_unit['id']])->count();
                $_unit['region_str'] = $area_map[$_unit['area_id']]['area_ip_desc'] ?? '';
                $_unit['card_total_money'] = M('internal_membership_card')->where(['card_name' => $cardName, 'unit_id' => $_unit['id']])->sum('balance_money');
                $_unit['card_recharge_money'] = M('internal_membership_card_log')->alias('l')
                ->join(C('DB_PREFIX') . 'internal_membership_card c ON l.card_id = c.id')
                ->where(['c.card_name' => $cardName, 'c.unit_id' => $_unit['id'], 'l.operation_type' => 1])
                ->sum('money');
            }
        } else {
            $units = [];
        }

        $this->assign('units', $units);
        $this->display();
    }
