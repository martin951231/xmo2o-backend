                $this->error('没有查询到数据');
            }

            $this->assign('internal_card',$res_card);

            $this->display();
        }else{
            //保存状态
            $time = time();
            $find_condition_card['card_id'] = $_POST['card_id'];
            $condition_card['status'] = $_POST['status'];
            $condition_card['last_time'] = time();
            $res = $card->where($find_condition_card)->find();

            if (!empty($_POST['store_id'])){
