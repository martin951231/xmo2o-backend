                //编辑
                $thisRecord = $mod->find($id);
                if (empty($thisRecord)) {
                    $this->error("修改记录不存在");
                }
                if ($mod->where(['card_name' => $cardName, 'id' => ['NEQ', $id]])->find()) {
                    $this->error("一卡通名称已存在，请更换");
                }
                $res = $mod->where(['id' => $id])->save($data);
                if ($res !== false) {
                    if ($thisRecord['card_name'] && $thisRecord['card_name'] <> $cardName) {
                        M('internal_membership_card')->where(['card_name'=>$thisRecord['card_name']])->save(['card_name'=>$cardName]);
                    }
                    $this->success("编辑成功");
                } else {
                    $this->error("编辑失败");
                }
            } else {
                //新增
                if ($mod->where(['card_name' => $cardName])->find()) {
                    $this->error("一卡通名称已存在，请更换");
                }
                $res = $mod->add($data);
                if ($res !== false) {
                    $this->success("添加成功");
                } else {
                    $this->error("添加失败");
                }
            }
        }

        $id = I('get.id',0,'intval');
        $record = [];
        if($id){
            $record = $mod->find($id);
        }
        $this->assign('record',$record);

        $admins = D('Admin')->where(['status'=>1,'realname'=>['NEQ','']])->field('id,account,realname')->select();
        $this->assign('admins', $admins);

