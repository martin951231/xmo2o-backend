            $storeId = D('Merchant_store')->where(['name' => $_GET['store_name']])->getField('store_id');
            $where['_string'] .=  $where['_string'] ?' AND ':''.' FIND_IN_SET("' . $storeId . '", p.use_store_ids)';
        }

        $join = 'left join ' . C('DB_PREFIX') . 'admin a ON p.admin_id = a.id ';
        $join .= 'left join ' . C('DB_PREFIX') . 'admin ba ON ba.id = p.belong_admin_id ';
        $join .= 'left join ' . C('DB_PREFIX') . 'merchant_store ms ON ms.store_id=p.store_id ';

        $count = $mod->alias('p')->field('p.*, a.account as admin_name')
            ->join($join)
            ->where($where)
            ->count();

        import('@.ORG.system_page');
