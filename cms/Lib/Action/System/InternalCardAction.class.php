    public function addCard()
    {
        if (IS_GET) {
            $internalUnit = [];
            if ($this->system_session['level'] <> 2) {
                $unitids = D('Admin')->getUnitIdsByAdmin($this->system_session);
                if ($unitids === false) {
                    $internalUnit = D('Internal_unit')->where(['area_id' => $this->admin_area_id])->select();
                } else {
                    if ($unitids) {
                        $where = ['id' => ['IN', $unitids]];
                        $this->admin_area_id > 0 && $where['area_id'] =   $this->admin_area_id;
                        $internalUnit = D('Internal_unit')->where($where)->select();
                    }
                }
            } else {
                $internalUnit = D('Internal_unit')->select();
            }
           
            $this->assign('internal_unit', $internalUnit);
            

            if ($this->system_session['level'] <> 2) {
                $cardTypes = D('Admin')->getCardTypeByAdmin($this->system_session);
                if(empty($cardTypes)){
                    $cardNames = [];
                }else{
                    $cardNames = D('Internal_membership_names')->where(['status' => 1,'card_name'=>['IN',$cardTypes]])->select();
                }
            }else{
                $cardNames = D('Internal_membership_names')->where(['status' => 1])->select();
            }
           
            $this->assign('card_names', $cardNames);
            $this->display();
            exit;
        }
        $cardName = I('card_name');
        $unitId = I('unit_id');
        $password = I('password');
        $phone = I('phone');
        $cardNo = I('card_id');
        $userName = I('user_name');
        $balanceMoney = floatval(I('balance_money'));
        $thisCard = M('Internal_membership_names')->where(['card_name' => $cardName])->find();
        if (!$thisCard) {
            $this->error('一卡通名称不存在');
        }
        $internalUnit = M('Internal_unit')->where(['id' => $unitId])->find();
        if (!$internalUnit) {
            $this->error('一卡通归属单位不存在');
        }
        if (strlen($password) != 6) {
            $this->error('密码格式错误，密码必须6位数');
        }
        if(!preg_match("/^[19][3456789]\d{9}$/", $phone) && !in_array($phone, C('sys_conf.special_internal_card_id'))) {
            $this->error('手机号格式错误');
        }
        $card = D('Internal_membership_card')->where(['card_id' => $cardNo])->find();
        if ($card){
            $this->error('一卡通卡号已存在');
        }
        
        $user = D('User')->where(['phone' => $phone])->find();
        $data = [
            'status' => 2, 
            'store_id' => $thisCard['store_id'], 
            'card_name' => $cardName, 
            'unit_id' => $unitId, 
            'company_owner' => $internalUnit['name'], 
            'province_id' => $internalUnit['province_id'],
            'city_id' => $internalUnit['city_id'],
            'area_id' => $internalUnit['area_id'],
            'password' => md5($password),
            'phone' => $phone,
            'card_id' => $cardNo,
            'user_name' => $userName,
            'balance_money' => $balanceMoney,
            'last_time' => time(),
        ];

        if ($user){
            $data['uid'] = $user['uid'];
            $data['is_bind'] = 1;
            $data['active_time'] = time();
        }
        $database = D('');
        $database->startTrans();
        $result = D('Internal_membership_card')->add($data);
        if (!$result) {
            $database->rollback();
            $this->error('操作失败');
        }
        $condition_card_log = [
            'card_id' => $cardNo,
            'system_id' => $this->system_session['id'],
            'describe' =>  "系统管理员{$this->system_session['account']}({$this->system_session['id']})".'新增一卡通, 默认余额 '.$balanceMoney.'元',
            'create_time' => time(),
            'operation_type' => 0
        ];
        if (!D('Internal_membership_card_log')->add($condition_card_log)) {
            $database->rollback();
            $this->error('操作失败');
        }
        $condition_card_log['operation_type'] = 1;
        $condition_card_log['before_balance'] = 0;
        $condition_card_log['after_balance'] = sprintf('%.2f', $balanceMoney);
        $condition_card_log['money'] = sprintf('%.2f', $balanceMoney);
        $condition_card_log['describe'] = "系统管理员{$this->system_session['account']}({$this->system_session['id']})".'导入一卡通, 充值默认余额 '.$condition_card_log['money'].'元,状态正常';
        if (!D('Internal_membership_card_log')->add($condition_card_log)) {
            $database->rollback();
            $this->error('操作失败');
        }
        $database->commit();
        $this->success('添加成功');
    }
