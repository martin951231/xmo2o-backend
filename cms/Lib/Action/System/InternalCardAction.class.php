    public function check_card(){
        if (IS_GET){
            return;
        }

        if (empty($_POST['status'])){
            $this->error('审核状态不能为空');
        }

        $time = time();
        $card = M('internal_membership_card');
        $card_log = M('internal_membership_card_log');

        $find_condition_card['card_id'] = $_POST['card_id'];
        $card_info = $card->where($find_condition_card)->find();
        $condition_card['status'] = $_POST['status'];
        if ($card_info['status'] == 10){
            $this->error('当前卡已被删除');
        }
        $condition_card['last_time'] = $time;
        $card->where($find_condition_card)->save($condition_card);

        //插入审核日志
        $status = '';
        $statusText = [
            0 => '禁止',
            1 => '正常',
            2 => '未审核',
        ];
        if(isset($statusText[$condition_card['status']])) {
            $status = $statusText[$condition_card['status']];
        }
        $condition_card_log['card_id'] = $find_condition_card['card_id'];
        $condition_card_log['operation_type'] = 0;
        $condition_card_log['system_id'] = $this->system_session['id'];
        $condition_card_log['create_time'] = $time;
        $condition_card_log['describe'] = "系统管理员{$this->system_session['account']}({$this->system_session['id']})".'操作, 当前余额'.$card_info['balance_money'].'元,状态'.$status;
        $card_log->add($condition_card_log);

        $this->success('操作成功');

    }

