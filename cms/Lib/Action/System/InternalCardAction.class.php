    public function recharge_balance()
    {
        $card = M('internal_membership_card');
        $card_log = M('internal_membership_card_log');
        if (!IS_POST){
            $find_condition_card['card_id'] = $_GET['card_id'];
            $internal_card = $card->where($find_condition_card)->find();
            $this->assign('internal_card',$internal_card);

            return $this->display();
        }

        $add_money = I('post.add_money', '', 'float');
        $card_id = I('post.card_id', 0, 'int');

        if (!is_numeric($add_money)) {
            $this->error('请填写正确的充值金额');
        }
        if ($add_money == 0) {
            $this->error('充值金额不能为0');
        }

        $time = time();
        $find_condition_card = [];
        $find_condition_card['card_id'] = $card_id;
        $before_card_info = $card->where($find_condition_card)->find();
        if (empty($before_card_info) || $before_card_info['status'] == 0) {
            $this->error('一卡通不存在或已禁用');
        }

        M()->startTrans();

        $money = round(floatval($add_money) * 100) / 100;
        $condition_card = [];
        $condition_card['balance_money'] = $money + $before_card_info['balance_money'];
        $condition_card['last_time'] = $time;
        $card_ret = $card->where($find_condition_card)->save($condition_card);
        if ($card_ret === false) {
            M()->rollback();
            $this->error('操作失败');
        }
        $after_card_info = $card->where($find_condition_card)->find();

        //插入审核日志
        if ($after_card_info['status'] == 0){
            $status = '禁止';
        }else if ($after_card_info['status'] == 1){
            $status = '正常';
        }else{
            $status = '未审核';
        }

        $batch_no = \internalCard\InternalCardService::genRechargeBatchNo();

