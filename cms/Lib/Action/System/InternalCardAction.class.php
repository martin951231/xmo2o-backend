    /**
     * 一卡通金额转移
     * @author Luo.Bao
     * @return void
     */
    public function transferCardMoney()
    {
        $before_card_id = I('post.before_card_id', '', 'trim,strip_tags');
        $after_card_id = I('post.after_card_id', '', 'trim,strip_tags');

        //获取转移前一卡通
        $before_card_info = M('internal_membership_card')->where(['card_id' => $before_card_id])->find();
        if (!$before_card_info) {
            $this->error('转移一卡通不存在');
        }
        if ($before_card_info['balance_money'] <= 0) {
            $this->error('转移一卡通余额小于等于0，不能转移');
        }

        //获取转移后一卡通
        $after_card_info = M('internal_membership_card')->where(['card_id' => $after_card_id])->find();
        if (!$after_card_info) {
            $this->error('转移后的一卡通不存在');
        }

        if ($before_card_info['phone'] != $after_card_info['phone']) {
            $this->error('转移前后一卡通手机号不一致，不能转移');
        }
        if ($before_card_info['uid'] != $after_card_info['uid']) {
            $this->error('转移前后一卡通用户不一致，不能转移');
        }
        if ($before_card_info['area_id'] != $after_card_info['area_id']) {
            $this->error('转移前后一卡通地区不一致，不能转移');
        }

        //开启事务
        D()->startTrans();
        //更新转移前一卡通金额为0
        $before_card_ret = M('internal_membership_card')->where(['card_id' => $before_card_id])->save(['balance_money' => 0, 'status' => 0]);
        if ($before_card_ret === false) {
            D()->rollback();
            $this->error('操作失败');
        }
        $before_update_log = [];
        $before_update_log['card_id'] = $before_card_id;
        $before_update_log['operation_type'] = 1;
        $before_update_log['before_balance'] = $before_card_info['balance_money'];
        $before_update_log['after_balance'] = 0;
        $before_update_log['money'] = $before_card_info['balance_money'] * -1;
        $before_update_log['system_id'] = $this->system_session['id'];
        $before_update_log['describe'] = "系统管理员{$this->system_session['id']}将旧卡{$before_card_id}余额转移到新卡{$after_card_id}，扣除余额" . sprintf('%.2f', $before_card_info['balance_money']) . '元';
        $before_update_log['create_time'] = time();
        $before_update_log['deduction_batch_no'] = '';
        $before_update_ret = M('internal_membership_card_log')->add($before_update_log);
        if (!$before_update_ret) {
            D()->rollback();
            $this->error('操作失败~');
        }
        //禁用转移前一卡通
        $before_del_log = [];
        $before_del_log['card_id'] = $before_card_id;
        $before_del_log['operation_type'] = 0;
        $before_del_log['system_id'] = $this->system_session['id'];
        $before_del_log['describe'] = "系统管理员{$this->system_session['id']}禁用一卡通({$before_card_id})";
        $before_del_log['create_time'] = time();
        $before_del_ret = M('internal_membership_card_log')->add($before_del_log);
        if (!$before_del_ret) {
            D()->rollback();
            $this->error('操作失败~~');
        }

        //更新转移后一卡通金额
        $after_balance = $after_card_info['balance_money'] + $before_card_info['balance_money'];
        $after_card_ret = M('internal_membership_card')->where(['card_id' => $after_card_id])->save(['balance_money' => $after_balance]);
        if ($after_card_ret === false) {
            D()->rollback();
            $this->error('操作失败~~~');
        }
        //创建转移后一卡通金额
        $after_update_log = [];
        $after_update_log['card_id'] = $after_card_id;
        $after_update_log['operation_type'] = 1;
        $after_update_log['before_balance'] = $after_card_info['balance_money'];
        $after_update_log['after_balance'] = $after_balance;
        $after_update_log['money'] = $before_card_info['balance_money'];
        $after_update_log['system_id'] = $this->system_session['id'];
        $after_update_log['describe'] = "系统管理员{$this->system_session['id']}将旧卡{$before_card_id}余额转移到新卡{$after_card_id}，增加余额" . sprintf('%.2f', $before_card_info['balance_money']) . '元';
        $after_update_log['create_time'] = time();
        $after_update_log['deduction_batch_no'] = '';
        $after_update_ret = M('internal_membership_card_log')->add($after_update_log);
        if (!$after_update_ret) {
            D()->rollback();
            $this->error('操作失败~~~~');
        }

        D()->commit();
        $this->success('操作成功');
    }

