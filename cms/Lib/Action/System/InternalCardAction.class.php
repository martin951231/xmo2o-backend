    public function add_card(){
        set_time_limit(0);
        if (IS_GET){
            $cardNames = D('internal_membership_names')->where(['status' => 1])->select();
            $this->assign('card_names', $cardNames);
            $this->display();
        }else{
            $card = M("internal_membership_card");
            $head_number = $_POST['head_number'];
            $start_number = $_POST['start_number'];
            $end_number = $_POST['end_number'];
            $card_name = $_POST['card_name'];
            $default_money = empty($_POST['default_money'])?0:(int)$_POST['default_money'];
            $head_number = $head_number<999999?$head_number*10:$head_number;
            $head_number *=100000;
            $last_time =$add_time= time();

            $tmp_data['balance_money']=$default_money;
            $tmp_data['create_time']=$last_time;
            $tmp_data['last_time']=$last_time;
            $tmp_data['card_name'] = $card_name;
            $data_arr =[];
            $i = $start_number;
            $h = 1;
            while($i<=$end_number){
                $data = $tmp_data;
                $data['card_id']= $head_number+$i;
                $data_arr[]  = $data;
                if($h%10000==0){
                    if(!$card->addAll($data_arr)){
                        $return = array('error'=>true,'msg'=>"添加实体卡失败!");
                        break;
                    }else{
                        $return = array('error'=>false,'msg'=>"添加成功! ");
                    }
                    $data_arr =[];
                }
                $i++;
                $h++;
            }

            if(!empty($data_arr)){
                if(!$card->addAll($data_arr)){
                    $return = array('error'=>true,'msg'=>"添加实体卡失败");
                }else{
                    $return = array('error'=>false,'msg'=>"添加成功! ");
                }
                $data_arr =[];
            }
            if(!$return['error']){
                $this->success($return['msg']);
            }else{
                $this->error($return['msg']);
            }
        }


    }

