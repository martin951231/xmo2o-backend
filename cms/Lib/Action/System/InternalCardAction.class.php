                ->join('as c left join pigcms_merchant_store s on c.store_id = s.store_id')
                ->where($condition_card)
                ->order($order_string)
                ->select();
            $s_excel = new \service\ExcelService();
            $first_line_map = [['ID', 'id'], ['一卡通名称', 'card_name'], ['一卡通ID', 'card_id'], ['用户ID', 'uid'], ['用户姓名', 'user_name'], ['用户手机号', 'phone'], ['归属单位', 'company_owner'], ['区域', 'region_str'], ['关联店铺名称', 'store_name'], ['关联店铺id', 'store_id'], ['激活时间', 'active_time'], ['最后修改时间', 'last_time'], ['卡余额', 'balance_money'], ['状态', 'status_text']];

