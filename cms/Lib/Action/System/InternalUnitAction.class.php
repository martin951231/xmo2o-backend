            $this->error('请选择归属单位');
        }
        //开启事务
        M()->startTrans();

        //插入一卡通充值抵扣记录
        $insert_deduction = [];
        $insert_deduction['unit_id'] = $unit_id;
        $insert_deduction['batch_no'] = \internalCard\InternalUnitService::genDeductionBatchNo();
        $insert_deduction['total_money'] = $money;
        $insert_deduction['create_system_id'] = $this->system_session['id'];
        $insert_deduction['use_time'] = $use_time;
        $insert_deduction['remark'] = $remark;
        $deduction_id = $m_internal_unit_deduction->add($insert_deduction);
        if (!$deduction_id) {
            M()->rollback();
            $this->error('操作失败');
        }

        //更新归属单位余额
        $unit_balance = \internalCard\InternalUnitService::updateUnitBalance($unit_id, $money);
        if (!$unit_balance) {
            M()->rollback();
            $this->error('操作失败');
        }

        M()->commit();
        $this->success('操作成功');
    }

    /**
     * 作废支出记录
     * @author Luo.Bao
     * @return void
     */
    public function deductionDel()
    {
        $deduction_id = I('post.deduction_id', 0, 'int');

        $m_internal_unit_deduction = M('internal_unit_deduction');
        $m_internal_unit = M('internal_unit');

        $deduction_info = $m_internal_unit_deduction->where(['id' => $deduction_id])->find();
        if (!$deduction_info) {
            $this->error('支出记录不存在');
        }
        if (time() - strtotime($deduction_info['create_time']) > $this->del_max_time) {
            $this->error('超过7天记录不能删除');
        }
        if ($deduction_info['delete_time'] > 0) {
            $this->error('记录已删除，请勿重复操作');
        }

        //开启事务
        M()->startTrans();

        //作废记录
        $ret = $m_internal_unit_deduction->where(['id' => $deduction_id])->save(['delete_time' => time()]);
        if ($ret === false) {
            M()->rollback();
            $this->error('操作失败');
        }

        //增加归属单位余额
        $unit_ret = $m_internal_unit->where(['id' => $deduction_info['unit_id']])->setInc('balance', $deduction_info['total_money']);
        if ($unit_ret === false) {
            M()->rollback();
            $this->error('操作失败');
        }

        M()->commit();
        $this->success('操作成功');
    }

