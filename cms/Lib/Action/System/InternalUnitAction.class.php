    /**
     * author:Luo
     * 添加、修改一卡通归属单位
     */
    public function unitSet()
    {
        $m_internal_unit = M('internal_unit');

        if (!IS_POST) {
            $id = I('get.id', 0, 'int');
            if ($id) {
                $info = $m_internal_unit->where(['id' => $id])->find();
            }

            $this->assign('info', $info ?? []);
            return $this->display('unit_set');
        }

        $id = I('post.id', 0, 'int');
        $unit_name = I('post.unit_name', '', 'trim,strip_tags');
        $contact_name = I('post.contact_name', '', 'trim,strip_tags');
        $contact_phone = I('post.contact_phone', '', 'trim,strip_tags');
        $province_id = I('post.province_id', 0, 'int');
        $city_id = I('post.city_id', 0, 'int');
        $area_id = I('post.area_id', 0, 'int');

        if (!$unit_name) {
            $this->error('请填写归属单位名称');
        }
        if (mb_strlen($unit_name, 'utf-8') > 50) {
            $this->error('归属单位名称不能超过50个汉字');
        }
        if (!$contact_name) {
            $this->error('请填写联系人');
        }
        if (mb_strlen($contact_name, 'utf-8') > 30) {
            $this->error('联系人名称不能超过30个汉字');
        }
        if (!$contact_phone) {
            $this->error('请填写联系人电话');
        }
        if (strlen($contact_phone) > 20) {
            $this->error('联系人电话不能超过20个字符');
        }

        $set_data = [];
        $set_data['name'] = $unit_name;
        $set_data['contact_name'] = $contact_name;
        $set_data['contact_phone'] = $contact_phone;
        if ($id) {
            $info = $m_internal_unit->where(['id' => $id])->find();
            if (!$info) {
                $this->error('归属单位不存在');
            }
            if ($m_internal_unit->where(['id' => ['neq',$id],'name'=>$unit_name])->find()) {
                $this->error('归属单位名称已存在，请更换');
            }

            $ret = $m_internal_unit->where(['id' => $id])->save($set_data);
            if ($ret === false) {
                $this->error('修改失败');
            }
        } else {
            if ($this->admin_area_id > 0) {
                $admin_area =  D('Area')->get_parents_area_by_areaid($this->admin_area_id);
                $province_id = $admin_area[1];
                $city_id = $admin_area[2];
                $area_id = $admin_area[3];
            }

            if (!$province_id || !$city_id || !$area_id) {
                $this->error('请选择所属区域');
            }

            if ($m_internal_unit->where(['name'=>$unit_name])->find()) {
                $this->error('归属单位名称已存在，请更换');
            }

            $set_data['province_id'] = $province_id;
            $set_data['city_id'] = $city_id;
            $set_data['area_id'] = $area_id;
            $set_data['create_system_id'] = $this->system_session['id'];
            $ret = $m_internal_unit->add($set_data);
            if (!$ret) {
                $this->error('添加失败');
            }
        }

        $this->success('操作成功');
    }

