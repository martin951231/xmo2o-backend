    /**
     * author:Luo
     * 一卡通归属单位列表
     */
    public function unitIndex()
    {
        $unit_name = I('get.unit_name', '', 'trim,strip_tags');
        $start_balance = I('get.start_balance', '', 'float');
        $end_balance = I('get.end_balance', '', 'float');
        $export = I('get.export', '', 'trim,strip_tags');
        $province_id = I('get.province_idss', 0, 'int');
        $city_id = I('get.city_idss', 0, 'int');
        $area_id = I('get.area_id', 0, 'int');

        $m_internal_unit = M('internal_unit');
        $m_admin = M('admin');
        $area_list = D('Area')->get_area_list();
        $area_map = array_column($area_list, null, 'area_id');

        $unit_con = [];
        if ($unit_name) {
            $unit_con[] = "name like('%{$unit_name}%')";
        }
        if ($start_balance !== '') {
            $unit_con[] = 'balance >= ' . $start_balance;
        }
        if ($end_balance !== '') {
            $unit_con[] = 'balance <= ' . $end_balance;
        }
        if ($province_id) {
            $unit_con[] = "province_id={$province_id}";
        }
        if ($city_id) {
            $unit_con[] = "city_id={$city_id}";
        }
        if ($area_id) {
            $unit_con[] = "area_id={$area_id}";
        }

        if ($this->admin_area_id > 0) {
           $unit_con[] = "area_id={$this->admin_area_id}";
        }

        if ($this->system_session['level'] <> 2) {
            $unitids = D('Admin')->getUnitIdsByAdmin($this->system_session);
            if ($unitids === false) {
                $unit_con[] = "area_id={$this->admin_area_id}";
            } else {
                if ($unitids) {
                    $unit_con[] = "id IN (" . implode(',', $unitids) . ")";
                } else {
                    $unit_con[] = "false";
                }
            }
        }

        $unit_where = implode(' AND ', $unit_con);
        if ($export == 'excel') {
            $list = $m_internal_unit->where($unit_where)->order('id desc')->select();
        } else {
            $unit_count = $m_internal_unit->where($unit_where)->count();
            $page = new Page($unit_count, 15);
            $list = $m_internal_unit->where($unit_where)->order('id desc')->limit($page->firstRow, $page->listRows)->select();
        }
        if ($list) {
            $admin_list = $m_admin->where(['id' => ['in', array_column($list, 'create_system_id')]])->select();
            $admin_map = array_column($admin_list, null, 'id');
        }
        $balanceMoney = $collectMoney = $usedMoney = 0;
        foreach ($list as &$_unit) {
            $_unit['admin_name'] = $admin_map[$_unit['create_system_id']]['account'] ?? '';
            $_unit['region_str'] = $area_map[$_unit['area_id']]['area_ip_desc'] ?? '';
            $balanceMoney += $_unit['balance'];
            $collectMoney += $_unit['total_money'];
            $usedMoney += $_unit['used_balance'];
        }

        if ($export == 'excel') {
            $s_excel = new \service\ExcelService();
            $first_line_map = [
                ['ID', 'id'], 
                ['归属单位名称', 'name'], 
                ['区域', 'region_str'], 
                ['联系人', 'contact_name'], 
                ['联系电话', 'contact_phone'],
                ['余额', 'balance'],
                ['总收款金额', 'total_money'], 
                ['总支出金额', 'used_money'], 
                ['操作员', 'admin_name'], 
                ['创建时间', 'create_time']
            ];
            $s_excel->exportExcel($first_line_map, $list, '归属单位');
            exit;
        }
        $sumInternalUnit = M('Internal_unit')
            ->where($unit_where)
            ->field('SUM(total_money) sumCollectMoney, SUM(balance) sumBalance, SUM(used_money) sumUsedMoney')
            ->find();
        
        $render_data = [
            'list' => $list,
            'pagebar' => $page->show()
        ];

        $this->assign('data', $render_data);
        $this->assign('sumInternalUnit', $sumInternalUnit);
        $this->assign('balance_money', $balanceMoney);
        $this->assign('collect_money', $collectMoney);
        $this->assign('used_balance', $usedMoney);

