    /**
     * author:Luo
     * 一卡通归属单位缴费
     * @return mixed
     */
    public function rechargeAdd()
    {
        $m_internal_unit = M('internal_unit');

        if (!IS_POST) {
            $unit_con = [];
            if ($this->admin_area_id > 0) {
                $unit_con['area_id'] = $this->admin_area_id;
            }
            $unit_list = $m_internal_unit->where($unit_con)->order('name asc')->select();
            $this->assign('unit_list', $unit_list);
            $this->assign('unit_id', I('get.unit_id', '', 'int'));
            return $this->display('recharge_add');
        }

        $money = I('post.money', 0, 'float');
        $unit_id = I('post.unit_id', 0, 'int');
        $payment_time = I('post.payment_time', '', 'trim,strip_tags');
        $remark = I('post.remark', '', 'trim,strip_tags');

        $m_internal_unit_recharge = M('internal_unit_recharge');

        if (!is_numeric($money) || $money <= 0) {
            $this->error('请输入正确的收款金额');
        }
        if (!$payment_time || !strtotime($payment_time . ' 00:00:00')) {
            $this->error('请选择正确的收款时间');
        }
        if (!$remark) {
            $this->error('请填写备注');
        }
        if (mb_strlen($remark, 'utf-8') > 150) {
            $this->error('备注不能超过150个汉字');
        }

        $unit_info = $m_internal_unit->where(['id' => $unit_id])->find();
        if (!$unit_info || ($this->admin_area_id > 0 && $unit_info['area_id'] != $this->admin_area_id)) {
            $this->error('请选择归属单位');
        }

        //开启事务
        M()->startTrans();

        $batch_no = \internalCard\InternalUnitService::genRechargeBatchNo();

        //插入收款记录
        $insert_recharge = [];
        $insert_recharge['unit_id'] = $unit_id;
        $insert_recharge['batch_no'] = $batch_no;
        $insert_recharge['money'] = $money;
        $insert_recharge['payment_time'] = $payment_time;
        $insert_recharge['create_system_id'] = $this->system_session['id'];
        $insert_recharge['remark'] = $remark;
        $recharge_id = $m_internal_unit_recharge->add($insert_recharge);
        if (!$recharge_id) {
            M()->rollback();
            $this->error('操作失败');
        }

        //更新归属单位余额
        $unit_balance = \internalCard\InternalUnitService::updateUnitBalance($unit_id, 0, $money);
        if (!$unit_balance) {
            M()->rollback();
            $this->error('操作失败');
        }

        M()->commit();
        $this->success('操作成功');
    }

    /**
     * 作废收款记录
     * @author Luo.Bao
     * @return void
     */
    public function rechargeDel()
    {
        $recharge_id = I('post.recharge_id', 0, 'int');

        $m_internal_unit_recharge = M('internal_unit_recharge');
        $m_internal_unit = M('internal_unit');

        $recharge_info = $m_internal_unit_recharge->where(['id' => $recharge_id])->find();
        if (!$recharge_info) {
            $this->error('收款记录不存在');
        }
        if (time() - strtotime($recharge_info['create_time']) > $this->del_max_time) {
            $this->error('超过7天记录不能删除');
        }
        if ($recharge_info['delete_time'] > 0) {
            $this->error('记录已删除，请勿重复操作');
        }

        //开启事务
        M()->startTrans();

        //标记记录作废
        $ret = $m_internal_unit_recharge->where(['id' => $recharge_id])->save(['delete_time' => time()]);
        if ($ret === false) {
            M()->rollback();
            $this->error('操作失败');
        }

        //减掉归属单位总金额和余额
        $unit_info = $m_internal_unit->where(['id' => $recharge_info['unit_id']])->find();
        $update_unit = [];
        $update_unit['balance'] = $unit_info['balance'] - $recharge_info['money'];
        $update_unit['total_money'] = $unit_info['total_money'] - $recharge_info['money'];
        $unit_ret = $m_internal_unit->where(['id' => $recharge_info['unit_id']])->save($update_unit);
        if ($unit_ret === false) {
            M()->rollback();
            $this->error('操作失败~');
        }

        M()->commit();
        $this->success('操作成功');
    }

